import { describe, it, expect } from 'vitest'
import {
  checkCommitMessage,
  checkTestCoverage,
  shouldHaveTests,
  checkTddCompliance,
  checkPRDescription,
  checkAllStandards,
  formatForCI,
  formatForCommittee,
  COVERAGE_THRESHOLD,
  AI_ATTRIBUTION_PATTERNS,
} from '@/lib/build/coding-standards'

/**
 * #357 GIT-5 — Coding standards enforcement tests. These test the PURE helpers
 * for validating commits, coverage, TDD compliance, and PR descriptions.
 *
 * Target: 80%+ coverage on the enforcement logic.
 */

describe('coding-standards enforcement (#357 GIT-5)', () => {
  describe('checkCommitMessage (pure)', () => {
    it('passes a clean commit message', () => {
      const result = checkCommitMessage('feat: add login button')
      expect(result.passed).toBe(true)
      expect(result.name).toBe('no-ai-attribution')
    })

    it('fails commit with Co-Authored-By: Claude', () => {
      const result = checkCommitMessage(`feat: add login

Co-Authored-By: Claude <noreply@anthropic.com>`)
      expect(result.passed).toBe(false)
      expect(result.reason).toContain('AI attribution')
    })

    it('fails commit with Co-Authored-By: ChatGPT', () => {
      const result = checkCommitMessage(`fix: bug

Co-Authored-By: ChatGPT <noreply@openai.com>`)
      expect(result.passed).toBe(false)
    })

    it('fails commit with "Generated by Claude"', () => {
      const result = checkCommitMessage('feat: add feature (Generated by Claude)')
      expect(result.passed).toBe(false)
    })

    it('fails commit with "Written by AI"', () => {
      const result = checkCommitMessage('fix: Written by AI assistant')
      expect(result.passed).toBe(false)
    })

    it('fails commit with "[Claude]" tag', () => {
      const result = checkCommitMessage('[Claude] feat: add feature')
      expect(result.passed).toBe(false)
    })

    it('is case-insensitive', () => {
      const result = checkCommitMessage('CO-AUTHORED-BY: CLAUDE')
      expect(result.passed).toBe(false)
    })

    it('passes similar but non-matching text', () => {
      const result = checkCommitMessage('fix: claude-like behavior in component')
      expect(result.passed).toBe(true)
    })
  })

  describe('checkTestCoverage (pure)', () => {
    it('passes at exactly threshold', () => {
      const result = checkTestCoverage(COVERAGE_THRESHOLD)
      expect(result.passed).toBe(true)
      expect(result.name).toBe('coverage-threshold')
    })

    it('passes above threshold', () => {
      const result = checkTestCoverage(95)
      expect(result.passed).toBe(true)
    })

    it('fails below threshold', () => {
      const result = checkTestCoverage(70)
      expect(result.passed).toBe(false)
      expect(result.reason).toContain('below threshold')
    })

    it('allows custom threshold', () => {
      const result = checkTestCoverage(70, 70)
      expect(result.passed).toBe(true)
    })

    it('rounds to 2 decimal places', () => {
      // 79.999 rounds to 80.00, which passes
      const result = checkTestCoverage(79.999)
      expect(result.passed).toBe(true)
      // 79.994 rounds to 79.99, which fails
      const result2 = checkTestCoverage(79.994)
      expect(result2.passed).toBe(false)
    })

    it('includes coverage details', () => {
      const result = checkTestCoverage(85)
      expect(result.details).toBeDefined()
      expect(result.details![0]).toContain('85%')
    })
  })

  describe('shouldHaveTests (pure)', () => {
    it('returns true for lib/*.ts files', () => {
      expect(shouldHaveTests('lib/build/something.ts')).toBe(true)
    })

    it('returns true for app/api/*.ts files', () => {
      expect(shouldHaveTests('app/api/route.ts')).toBe(true)
    })

    it('returns true for components/*.tsx files', () => {
      expect(shouldHaveTests('components/Button.tsx')).toBe(true)
    })

    it('returns false for test files', () => {
      expect(shouldHaveTests('lib/build/something.test.ts')).toBe(false)
    })

    it('returns false for spec files', () => {
      expect(shouldHaveTests('lib/build/something.spec.ts')).toBe(false)
    })

    it('returns false for __tests__ files', () => {
      expect(shouldHaveTests('__tests__/lib/build/something.test.ts')).toBe(false)
    })

    it('returns false for e2e files', () => {
      expect(shouldHaveTests('e2e/login.spec.ts')).toBe(false)
    })

    it('returns false for type definition files', () => {
      expect(shouldHaveTests('lib/types.d.ts')).toBe(false)
    })

    it('returns false for config files', () => {
      expect(shouldHaveTests('vitest.config.ts')).toBe(false)
    })

    it('normalizes Windows paths', () => {
      expect(shouldHaveTests('lib\\build\\something.ts')).toBe(true)
    })
  })

  describe('checkTddCompliance (pure)', () => {
    it('passes when all changed files have tests', () => {
      const result = checkTddCompliance(
        ['lib/build/feature.ts'],
        ['__tests__/lib/build/feature.test.ts']
      )
      expect(result.passed).toBe(true)
      expect(result.name).toBe('tdd-compliance')
    })

    it('passes when no testable files in changeset', () => {
      const result = checkTddCompliance(
        ['README.md', 'package.json'],
        []
      )
      expect(result.passed).toBe(true)
      expect(result.details![0]).toContain('No testable files')
    })

    it('fails when changed files lack tests', () => {
      const result = checkTddCompliance(
        ['lib/build/feature.ts', 'lib/build/another.ts'],
        ['__tests__/lib/build/feature.test.ts']
      )
      expect(result.passed).toBe(false)
      expect(result.reason).toContain('lack test coverage')
      expect(result.details).toContain('Missing tests for: lib/build/another.ts')
    })

    it('ignores test files in changeset', () => {
      const result = checkTddCompliance(
        ['lib/build/feature.test.ts'],
        []
      )
      expect(result.passed).toBe(true)
    })

    it('matches tests by base name', () => {
      const result = checkTddCompliance(
        ['lib/git/gitea-client.ts'],
        ['__tests__/lib/git/gitea-client-354.test.ts']
      )
      expect(result.passed).toBe(true)
    })
  })

  describe('checkPRDescription (pure)', () => {
    it('passes a valid PR title', () => {
      const result = checkPRDescription('feat: add login functionality')
      expect(result.passed).toBe(true)
      expect(result.name).toBe('pr-description')
    })

    it('fails short PR title', () => {
      const result = checkPRDescription('fix')
      expect(result.passed).toBe(false)
      expect(result.reason).toContain('too short')
    })

    it('fails PR with AI attribution in title', () => {
      const result = checkPRDescription('[Claude] feat: add feature')
      expect(result.passed).toBe(false)
      expect(result.reason).toContain('AI attribution')
    })

    it('fails PR with AI attribution in body', () => {
      const result = checkPRDescription(
        'feat: add feature',
        'Generated by Claude'
      )
      expect(result.passed).toBe(false)
    })

    it('passes PR with clean body', () => {
      const result = checkPRDescription(
        'feat: add login button',
        'This PR adds a login button to the header.'
      )
      expect(result.passed).toBe(true)
    })
  })

  describe('checkAllStandards (aggregator)', () => {
    it('runs all checks when all inputs provided', () => {
      const result = checkAllStandards({
        commitMessage: 'feat: add feature',
        coverage: 85,
        changedFiles: ['lib/build/feature.ts'],
        testFiles: ['__tests__/lib/build/feature.test.ts'],
        prTitle: 'feat: add feature',
      })
      expect(result.passed).toBe(true)
      expect(result.checks).toHaveLength(4)
    })

    it('only runs checks for provided inputs', () => {
      const result = checkAllStandards({
        commitMessage: 'feat: add feature',
      })
      expect(result.checks).toHaveLength(1)
      expect(result.checks[0].name).toBe('no-ai-attribution')
    })

    it('reports failures correctly', () => {
      const result = checkAllStandards({
        commitMessage: 'feat: add feature',
        coverage: 50,
      })
      expect(result.passed).toBe(false)
      expect(result.summary).toContain('failed')
      expect(result.summary).toContain('coverage-threshold')
    })

    it('handles empty options', () => {
      const result = checkAllStandards({})
      expect(result.passed).toBe(true)
      expect(result.checks).toHaveLength(0)
    })
  })

  describe('formatForCI (pure)', () => {
    it('formats passing result', () => {
      const result = checkAllStandards({ commitMessage: 'feat: ok' })
      const output = formatForCI(result)
      expect(output).toContain('## Coding Standards Check')
      expect(output).toContain('✅ **All checks passed**')
    })

    it('formats failing result', () => {
      const result = checkAllStandards({ coverage: 50 })
      const output = formatForCI(result)
      expect(output).toContain('❌ **Some checks failed**')
      expect(output).toContain('coverage-threshold')
    })

    it('includes details for each check', () => {
      const result = checkAllStandards({
        commitMessage: 'feat: ok',
        coverage: 85,
      })
      const output = formatForCI(result)
      expect(output).toContain('no-ai-attribution')
      expect(output).toContain('coverage-threshold')
    })
  })

  describe('formatForCommittee (pure)', () => {
    it('returns approve for passing result', () => {
      const result = checkAllStandards({ commitMessage: 'feat: ok' })
      const committee = formatForCommittee(result)
      expect(committee.verdict).toBe('approve')
    })

    it('returns request-changes for failing result', () => {
      const result = checkAllStandards({ coverage: 50 })
      const committee = formatForCommittee(result)
      expect(committee.verdict).toBe('request-changes')
    })

    it('includes summary and details', () => {
      const result = checkAllStandards({ commitMessage: 'feat: ok' })
      const committee = formatForCommittee(result)
      expect(committee.summary).toBeDefined()
      expect(committee.details).toContain('## Coding Standards Check')
    })
  })

  describe('AI_ATTRIBUTION_PATTERNS coverage', () => {
    const testCases = [
      ['Co-Authored-By: Claude <noreply@anthropic.com>', false],
      ['Co-Authored-By: Anthropic <noreply@anthropic.com>', false],
      ['Co-Authored-By: ChatGPT <noreply@openai.com>', false],
      ['Co-Authored-By: OpenAI <noreply@openai.com>', false],
      ['Co-Authored-By: Copilot <noreply@github.com>', false],
      ['Generated by Claude', false],
      ['Generated by ChatGPT', false],
      ['Generated by AI', false],
      ['Written by GPT', false],
      ['Created by Claude', false],
      ['Assisted by AI', false],
      ['With help from Claude', false],
      ['🤖 Claude', false],
      ['Claude 🤖', false],
      ['[Claude]', false],
      ['[ChatGPT]', false],
      ['[Copilot]', false],
      ['Regular commit message', true],
      ['fix: claude variable name', true],
    ] as const

    for (const [message, shouldPass] of testCases) {
      it(`${shouldPass ? 'passes' : 'fails'}: "${message}"`, () => {
        const result = checkCommitMessage(message)
        expect(result.passed).toBe(shouldPass)
      })
    }
  })
})

describe('performance characteristics', () => {
  it('checkCommitMessage is O(n) in pattern count', () => {
    const start = performance.now()
    for (let i = 0; i < 10000; i++) {
      checkCommitMessage('feat: add some feature with a reasonably long message')
    }
    const elapsed = performance.now() - start
    expect(elapsed).toBeLessThan(500)
  })

  it('checkTddCompliance is O(n*m) in files', () => {
    const changedFiles = Array.from({ length: 50 }, (_, i) => `lib/build/file${i}.ts`)
    const testFiles = Array.from({ length: 50 }, (_, i) => `__tests__/lib/build/file${i}.test.ts`)

    const start = performance.now()
    for (let i = 0; i < 100; i++) {
      checkTddCompliance(changedFiles, testFiles)
    }
    const elapsed = performance.now() - start
    expect(elapsed).toBeLessThan(500)
  })
})
