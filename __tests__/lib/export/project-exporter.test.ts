import { describe, it, expect } from 'vitest'
import JSZip from 'jszip'
import { exportProject } from '@/lib/export/project-exporter'

/**
 * Issue #1201 — Coverage Phase 1: lib/ pure logic to 80%.
 *
 * exportProject() is pure in-memory zip generation (no I/O beyond jszip's
 * own in-memory buffer work), so we run the real jszip library both ways:
 * to build the zip, and to load it back and inspect its real contents.
 */

async function loadZip(bytes: Uint8Array) {
  return new JSZip().loadAsync(bytes)
}

describe('#1201 exportProject', () => {
  it('returns a real non-empty Uint8Array', async () => {
    const result = await exportProject(
      { 'src/App.tsx': 'export default function App(){}' },
      'My Cool App'
    )

    expect(result).toBeInstanceOf(Uint8Array)
    expect(result.length).toBeGreaterThan(0)
  })

  it('minimal input: preserves the supplied file and auto-injects every default scaffold file', async () => {
    const result = await exportProject(
      { 'src/App.tsx': 'export default function App(){}' },
      'My Cool App'
    )
    const zip = await loadZip(result)

    const appFile = zip.file('src/App.tsx')
    expect(appFile).not.toBeNull()
    expect(await appFile!.async('string')).toBe('export default function App(){}')

    // package.json auto-added, slugified name derived from appName
    const pkgFile = zip.file('package.json')
    expect(pkgFile).not.toBeNull()
    const pkg = JSON.parse(await pkgFile!.async('string'))
    expect(pkg.name).toBe('my-cool-app')
    expect(pkg.dependencies.next).toBeDefined()
    expect(pkg.dependencies.react).toBeDefined()
    expect(pkg.dependencies['react-dom']).toBeDefined()
    expect(pkg.dependencies['lucide-react']).toBeDefined()
    expect(pkg.dependencies.recharts).toBeDefined()
    expect(pkg.dependencies.clsx).toBeDefined()
    expect(pkg.dependencies['tailwind-merge']).toBeDefined()
    expect(pkg.devDependencies.typescript).toBeDefined()
    expect(pkg.devDependencies.tailwindcss).toBeDefined()

    const tsconfigFile = zip.file('tsconfig.json')
    expect(tsconfigFile).not.toBeNull()
    expect(await tsconfigFile!.async('string')).toContain('"compilerOptions"')

    const nextConfigFile = zip.file('next.config.js')
    expect(nextConfigFile).not.toBeNull()
    expect(await nextConfigFile!.async('string')).toContain('nextConfig')

    const tailwindFile = zip.file('tailwind.config.js')
    expect(tailwindFile).not.toBeNull()
    expect(await tailwindFile!.async('string')).toContain('tailwindcss')

    const postcssFile = zip.file('postcss.config.js')
    expect(postcssFile).not.toBeNull()
    expect(await postcssFile!.async('string')).toContain('autoprefixer')

    const readmeFile = zip.file('README.md')
    expect(readmeFile).not.toBeNull()
    const readmeContent = await readmeFile!.async('string')
    expect(readmeContent).toContain('Generated by [AINative Builder Studio]')
    expect(readmeContent).toContain('npm install')
    expect(readmeContent).toContain('npm run dev')

    const gitignoreFile = zip.file('.gitignore')
    expect(gitignoreFile).not.toBeNull()
    expect(await gitignoreFile!.async('string')).toBe(
      'node_modules/\n.next/\n.env\n.env.local\n'
    )
  })

  it('preserves a user-supplied package.json verbatim and skips default injection', async () => {
    const customPkg = '{"name":"custom"}'
    const result = await exportProject(
      { 'package.json': customPkg, 'src/App.tsx': 'x' },
      'Whatever'
    )
    const zip = await loadZip(result)

    const pkgFile = zip.file('package.json')
    expect(pkgFile).not.toBeNull()
    expect(await pkgFile!.async('string')).toBe(customPkg)
  })

  it('preserves a user-supplied tsconfig.json and still injects the other defaults', async () => {
    const customTsconfig = '{"custom":true}'
    const result = await exportProject(
      { 'tsconfig.json': customTsconfig, 'src/App.tsx': 'x' },
      'Whatever'
    )
    const zip = await loadZip(result)

    expect(await zip.file('tsconfig.json')!.async('string')).toBe(customTsconfig)

    // other defaults still injected
    expect(zip.file('package.json')).not.toBeNull()
    expect(zip.file('next.config.js')).not.toBeNull()
    expect(zip.file('tailwind.config.js')).not.toBeNull()
    expect(zip.file('postcss.config.js')).not.toBeNull()
    expect(zip.file('README.md')).not.toBeNull()
    expect(zip.file('.gitignore')).not.toBeNull()
  })

  it('a supplied tailwind.config.ts (not .js) suppresses default tailwind.config.js injection entirely', async () => {
    const customTailwindTs = 'export default { content: [] }'
    const result = await exportProject(
      { 'tailwind.config.ts': customTailwindTs, 'src/App.tsx': 'x' },
      'Whatever'
    )
    const zip = await loadZip(result)

    expect(await zip.file('tailwind.config.ts')!.async('string')).toBe(customTailwindTs)
    expect(zip.file('tailwind.config.js')).toBeNull()
  })

  it('strips a single leading slash from input file paths when storing in the zip', async () => {
    const result = await exportProject(
      { '/src/App.tsx': 'leading-slash-content' },
      'Whatever'
    )
    const zip = await loadZip(result)

    expect(zip.file('/src/App.tsx')).toBeNull()
    const file = zip.file('src/App.tsx')
    expect(file).not.toBeNull()
    expect(await file!.async('string')).toBe('leading-slash-content')
  })

  it('leading-slash package.json key also suppresses default package.json injection', async () => {
    const customPkg = '{"name":"slash-variant"}'
    const result = await exportProject(
      { '/package.json': customPkg, 'src/App.tsx': 'x' },
      'Whatever'
    )
    const zip = await loadZip(result)

    // stored without the leading slash
    const pkgFile = zip.file('package.json')
    expect(pkgFile).not.toBeNull()
    expect(await pkgFile!.async('string')).toBe(customPkg)

    // no duplicate/overwritten default was injected under a different key
    expect(zip.file('/package.json')).toBeNull()
  })

  it('slugifies an appName with punctuation per the literal regex (each disallowed char becomes its own hyphen)', async () => {
    const result = await exportProject({ 'src/App.tsx': 'x' }, "Jane's App!! 2.0")
    const zip = await loadZip(result)

    const pkg = JSON.parse(await zip.file('package.json')!.async('string'))
    // "jane's app!! 2.0".replace(/[^a-z0-9-]/g, '-') -> "jane-s-app---2-0"
    expect(pkg.name).toBe('jane-s-app---2-0')
  })

  it('README.md interpolates the raw (non-slugified) appName, distinct from the slugified package.json name', async () => {
    const result = await exportProject({ 'src/App.tsx': 'x' }, 'My Cool App')
    const zip = await loadZip(result)

    const readme = await zip.file('README.md')!.async('string')
    expect(readme).toContain('# My Cool App')
    expect(readme).not.toContain('# my-cool-app')

    const pkg = JSON.parse(await zip.file('package.json')!.async('string'))
    expect(pkg.name).toBe('my-cool-app')
  })
})
